_tooltip_window = None  # module-level reference to the current tooltip Toplevel
_dismiss_bound_windows = set()  # windows already wired to dismiss the tooltip on focus-out

def display_widget_info(window, e, x_coordinate, y_coordinate, x_coordinate_hover_over, text_info):
    global _tooltip_window
    # Destroy any existing tooltip first
    if _tooltip_window is not None:
        try:
            _tooltip_window.destroy()
        except:
            pass
        _tooltip_window = None

    # Create a Toplevel tooltip window (floats above, does not steal mouse events)
    _tooltip_window = tk.Toplevel(window)
    _tooltip_window.wm_overrideredirect(True)  # no window decorations
    _tooltip_window.wm_attributes('-topmost', True)  # stay on top

    # wraplength keeps a long one-line message from running off the right edge: it wraps to
    # multiple lines within (roughly) the main window's width instead of one very wide line.
    try:
        win_w = window.winfo_width()
    except Exception:
        win_w = 0
    wrap = win_w - 60 if win_w and win_w > 260 else 700

    # Same dark-card surface as GUI_theme_util.ToolTip -- the two tooltip implementations must not
    # look like two different products. Colors are sourced from there so there is one definition.
    try:
        import GUI_theme_util
        tip_bg, tip_fg, tip_border = (GUI_theme_util._TIP_BG, GUI_theme_util._TIP_TEXT,
                                      GUI_theme_util._TIP_BORDER)
    except Exception:
        tip_bg, tip_fg, tip_border = '#24262b', '#f2f3f5', '#3a3d44'

    _tooltip_window.configure(background=tip_border)
    tooltip_lb = tk.Label(_tooltip_window, text=text_info, foreground=tip_fg,
                          background=tip_bg, anchor='w', justify='left',
                          borderwidth=0,
                          padx=8, pady=6, wraplength=wrap,
                          font=('TkDefaultFont', 9))
    tooltip_lb.pack(padx=1, pady=1)

    # Position in screen coordinates relative to the main window
    win_x = window.winfo_rootx()
    win_y = window.winfo_rooty()

    # After packing, read the tooltip's ACTUAL size, then keep it fully ON-SCREEN: if it would
    # run off the right edge, shift it left; never let it start off the left edge either.
    _tooltip_window.update_idletasks()
    tip_w = _tooltip_window.winfo_reqwidth()
    tip_height = _tooltip_window.winfo_reqheight()
    screen_w = window.winfo_screenwidth()
    tip_x = win_x + x_coordinate_hover_over
    if tip_x + tip_w > screen_w - 10:
        tip_x = screen_w - tip_w - 10
    if tip_x < 10:
        tip_x = 10
    tip_y = win_y + y_coordinate - tip_height - 2  # 2px gap above widget

    _tooltip_window.wm_geometry(f"+{int(tip_x)}+{int(tip_y)}")

    # Safety net: guarantee the tooltip disappears even if <Leave>/<Button> never fire (e.g. a
    # pointer grab). Auto-hide THIS specific tooltip after a few seconds no matter what.
    _this_tip = _tooltip_window
    def _auto_hide(_w=_this_tip):
        global _tooltip_window
        try:
            _w.destroy()
        except Exception:
            pass
        if _tooltip_window is _w:
            _tooltip_window = None
    try:
        _this_tip.after(6000, _auto_hide)
    except Exception:
        pass

    # Kill the tooltip when the window loses focus -- e.g. you launch another GUI or open a dropdown
    # menu -- so a tooltip can never stay stuck on screen across GUIs. Bind ONCE per window.
    try:
        if window not in _dismiss_bound_windows:
            # FocusOut: leaving the window (launching another GUI). Button: any click anywhere -- events
            # on child widgets propagate to the toplevel bindtag, so this also covers custom-bound
            # tooltips (e.g. the welcome screen's ENTER button) that never go through hover_over_widget.
            window.bind('<FocusOut>', lambda e: delete_display_widget_lb(window, e, ''), add='+')
            window.bind('<Button>', lambda e: delete_display_widget_lb(window, e, ''), add='+')
            _dismiss_bound_windows.add(window)
    except Exception:
        pass

def delete_display_widget_lb(window, e, text_info):
    global _tooltip_window
    if _tooltip_window is not None:
        try:
            _tooltip_window.destroy()
        except:
            pass
        _tooltip_window = None

# https://stackoverflow.com/questions/20399243/display-message-when-hovering-over-something-with-mouse-cursor-in-python
